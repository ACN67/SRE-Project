"""Deterministic LoCoMo answer policy and hybrid evidence rendering.

The benchmark answer model returns plain text.  Evidence references are
constructed from the exact source turns included in the prompt rather than
being generated by the model.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from typing import Callable

from dynamic_memory.contracts import MemoryRecord, QueryRequest, SourceRef, SourceTurn
from dynamic_memory.data.repository import SourceRepository


class BenchmarkProtocolError(ValueError):
    """Sanitized protocol failure that never embeds private source text."""

    def __init__(self, code: str) -> None:
        self.code = code
        super().__init__(f"{code}: benchmark protocol failed")


@dataclass(frozen=True, slots=True)
class BenchmarkQuestion:
    query_id: str
    category: int
    adversarial_answer: str | None = None


@dataclass(frozen=True, slots=True)
class HybridContext:
    text: str
    memories: tuple[MemoryRecord, ...]
    source_turns: tuple[SourceTurn, ...]
    source_refs: tuple[SourceRef, ...]


def _option_order(query_id: str, adversarial_answer: str) -> tuple[str, str]:
    seed = int(hashlib.sha256(query_id.encode("utf-8")).hexdigest()[:16], 16)
    answers = (adversarial_answer, "No information available")
    return answers if seed % 2 == 0 else tuple(reversed(answers))


def render_question(
    request: QueryRequest,
    policy: BenchmarkQuestion,
    *,
    session_dates: dict[str, str] | None = None,
) -> str:
    """Render one LoCoMo question without exposing a reference answer."""
    if request.query_id != policy.query_id:
        raise BenchmarkProtocolError("QUERY_MISMATCH")
    if policy.category not in range(1, 6):
        raise BenchmarkProtocolError("CATEGORY_INVALID")
    common = (
        "Answer using only the supplied conversation evidence. "
        "Return only the answer text: no Markdown, no explanation, no prefix, "
        "and no complete sentence when a short phrase is sufficient.\n"
    )
    if policy.category == 1:
        instruction = (
            "If several separate answers apply, list every supported answer "
            "and separate them with commas."
        )
    elif policy.category == 2:
        dates = ""
        if session_dates:
            dates = " Session dates: " + json.dumps(
                session_dates, ensure_ascii=False, sort_keys=True
            ) + "."
        instruction = (
            "Answer with the approximate date supported by the conversation."
            + dates
            + " Resolve relative expressions against the relevant session date. "
            "Keep the natural date granularity used by the evidence; do not "
            "replace an approximate month or week with a fake exact day."
        )
    elif policy.category == 3:
        instruction = (
            "Give the shortest concrete answer that follows from the supplied "
            "personal facts. A cautious, evidence-grounded general inference is "
            "allowed; do not invent private events."
        )
    elif policy.category == 4:
        instruction = "Give the shortest direct answer supported by the evidence."
    else:
        if not isinstance(policy.adversarial_answer, str) or not policy.adversarial_answer.strip():
            raise BenchmarkProtocolError("ADVERSARIAL_OPTION_MISSING")
        first, second = _option_order(request.query_id, policy.adversarial_answer.strip())
        instruction = (
            "Choose exactly one option and return only its text:\n"
            f"Option A: {first}\nOption B: {second}"
        )
    return f"{request.question}\n\n{common}{instruction}"


def _render_turn(
    turn: SourceTurn,
    metadata_lookup: Callable[[str, SourceRef], dict] | None,
) -> str:
    ref = SourceRef(session_id=turn.session_id, dia_id=turn.dia_id)
    metadata = metadata_lookup(turn.sample_id, ref) if metadata_lookup is not None else {}
    fields = {
        "source_ref": ref.model_dump(mode="json"),
        "speaker": turn.speaker,
        "text": turn.text,
        **{key: value for key, value in metadata.items() if value not in (None, "", [], {})},
    }
    if turn.image_caption:
        fields["image_caption"] = turn.image_caption
        fields["caption_origin"] = turn.caption_origin
    if turn.recorded_at is not None:
        fields["recorded_at"] = turn.recorded_at.isoformat()
    return json.dumps(fields, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def build_hybrid_context(
    memories: list[MemoryRecord],
    repository: SourceRepository | None,
    *,
    max_memories: int = 8,
    metadata_lookup: Callable[[str, SourceRef], dict] | None = None,
) -> HybridContext:
    """Render ranked facts followed by their exact, source-deduplicated turns."""
    if type(max_memories) is not int or max_memories < 1:
        raise BenchmarkProtocolError("CONTEXT_LIMIT_INVALID")
    selected = tuple(memories[:max_memories])
    fact_rows = [memory.model_dump(mode="json") for memory in selected]
    turns: list[SourceTurn] = []
    refs: list[SourceRef] = []
    seen: set[tuple[str, str]] = set()
    if repository is not None:
        for memory in selected:
            for ref in memory.source_refs:
                key = (ref.session_id, ref.dia_id)
                if key in seen:
                    continue
                seen.add(key)
                try:
                    turn = repository.get_turn(memory.sample_id, ref)
                except Exception:
                    raise BenchmarkProtocolError("SOURCE_NOT_FOUND") from None
                turns.append(turn)
                refs.append(ref)
    parts = ["ANSWERABLE FACTS:", json.dumps(fact_rows, ensure_ascii=False, sort_keys=True)]
    if turns:
        parts.extend(("SOURCE TURNS:", "\n".join(_render_turn(turn, metadata_lookup) for turn in turns)))
    return HybridContext(
        text="\n\n".join(parts),
        memories=selected,
        source_turns=tuple(turns),
        source_refs=tuple(refs),
    )


def context_refs(context: HybridContext) -> list[SourceRef]:
    if context.source_refs:
        return list(context.source_refs)
    return [
        ref
        for memory in context.memories
        for ref in memory.source_refs
    ]
